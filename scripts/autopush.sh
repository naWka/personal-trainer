#!/usr/bin/env bash
#
# Stop-хук: не даёт правкам залежаться локально.
#
# Атлет попросил, чтобы изменения сразу ехали в main и на сайт, а не копились
# в ветке или в незапушенных коммитах. Логика намеренно осторожная:
#
#   - не на main            → громко напомнить, ничего не делать
#   - есть коммиты          → прогнать validate.py и запушить
#   - грязное дерево        → напомнить отдельной строкой, НЕ коммитить за
#                             агента: коммит это решение о том, что считать
#                             законченным
#   - пушить нечего, чисто  → молчать
#
# Порядок важен, и он был неверным до 2026-08-16: проверка грязного дерева
# стояла ПЕРЕД пушем и выходила из хука. Достаточно было одного неотслеживаемого
# файла в папке — и уже закоммиченные данные переставали уезжать на сайт совсем.
# Так и вышло: незакоммиченный data/poses.json задержал в локальном клоне
# синхронизацию Oura, и атлет не видел на сайте ночь, которая лежала на диске.
# Коммит — это уже принятое решение, и грязное соседнее дерево к нему отношения
# не имеет: push отправляет коммиты, а не рабочую папку.
#
# Хук никогда не блокирует остановку: любой отказ это только systemMessage.

set -uo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.." || exit 0
git rev-parse --git-dir >/dev/null 2>&1 || exit 0

# systemMessage — единственный способ показать текст пользователю из Stop-хука.
say() {
  python3 -c 'import json,sys; print(json.dumps({"systemMessage": sys.argv[1]}))' "$1"
  exit 0
}

branch=$(git rev-parse --abbrev-ref HEAD 2>/dev/null) || exit 0

if [ "$branch" != "main" ]; then
  say "Автопуш не сработал: HEAD на ветке «$branch», а не на main. Правки на сайт не поедут. Перенести: git push origin HEAD:main"
fi

# Незакоммиченное — это отдельная новость, а не причина не пушить. Строка
# копится и договаривается в самом конце, после того как коммиты уехали.
dirty=""
if [ -n "$(git status --porcelain)" ]; then
  files=$(git status --porcelain | sed 's/^/  /' | head -20)
  dirty="
Незакоммиченное на main осталось — коммит за агента хук не делает:
$files"
  # Файл в data/, которого нет в git, — это данные, которых нет ни на сайте, ни
  # в резервной копии. Отдельная строка, потому что цена другая.
  lost=$(git status --porcelain data/ | sed 's/^/  /' | head -10)
  if [ -n "$lost" ]; then
    dirty="$dirty
Из этого в data/ — то есть история, которой нет нигде, кроме этого диска:
$lost"
  fi
fi

ahead=$(git rev-list --count origin/main..HEAD 2>/dev/null || echo 0)

if [ "$ahead" -eq 0 ]; then
  [ -n "$dirty" ] && say "Пушить нечего.$dirty"
  exit 0
fi

if ! validation=$(python3 scripts/validate.py 2>&1); then
  say "Автопуш остановлен: scripts/validate.py упал, в main такое не едет.
$validation$dirty"
fi

if ! push=$(git push origin main 2>&1); then
  say "Автопуш не удался: git push origin main вернул ошибку.
$push$dirty"
fi

say "Автопуш: $ahead коммит(ов) уехало в main, деплой запущен.$dirty"
